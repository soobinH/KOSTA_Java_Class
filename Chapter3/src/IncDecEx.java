
// 연산자 예제
public class IncDecEx {

	public static void main(String[] args) {
		int n = 10;
		System.out.println(++n);
		System.out.println(n++);
		System.out.println(n);
		
		System.out.println();
		
		System.out.println(--n);
		System.out.println(n--);
		System.out.println(n);
		
		System.out.println("==============");
		
		int r = 5+3;
		int m = 1;
		int rm1 = m++;
		System.out.println(rm1);
		System.out.println(rm1);

	}

}
